% [A , c] = MinVolEllipse(P, tolerance)
% Finds the minimum volume enclsing ellipsoid (MVEE) of a set of data
% points stored in matrix P. The following optimization problem is solved:
%
% minimize       log(det(A))
% subject to     (P_i - c)' * A * (P_i - c) <= 1
%
