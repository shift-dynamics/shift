#define _GNU_SOURCE
#include <assert.h>
#include <err.h>
#include <locale.h>
#include <math.h>
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <errno.h>
#include <sys/mman.h>
#include <sys/stat.h>
#include <unistd.h>

#include "phf.h"

/*
See C argc and argv for examples on how to use argc and argv[].
*/
int main(int argc, char** argv) {
  /*
  Output hash space loading factor as percentage from 1...100. 100% generates a
  minimal perfect hash function. Does not implement the necessary optimizations
  to ensure timely generation of minimal perfect hass functions. Normally want a
  loading factor of 80% to 90% for large key sets. Small key sets as used here
  alpha = 100 is best.
  */
  size_t alpha = 100;
  /*
  Number of keys per bucket when generating the g() function mapping.
  */
  size_t lambda = 4;
  /*
  Random integer seed. Make seed also random?
  */
  phf_seed_t seed = 42;
  /*
  If nodiv == 1, r and m are rounded to powers of 2 and modular reduction is
  performed using bitwise AND. Otherwise if nodiv == 0, r and m are rounded up
  to the nearest primes and modulo division is used when indexing
  tables.Rounding occurs after calculation of the intermediate and output hash
  table loading.More important when building small hash tables with the C
  interface. Optimization is substantial when the compiler can inline the code.
  */
  int nodiv = 0;

  /*
  Removing this statement appears to have no effect on the results.
  */
  // setlocale(LC_ALL, "C");

  /*
  typedef struct phf_string {
    void* p;
    size_t n;
  } phf_string_t;
  p points to an eight byte string capable of holding up to seven characters.
  0<n<8 indicates the number of characters in the string.
  Set up for an array of 100 test keys, each five characters long.
  */
  phf_string_t keys[100];
  for(int i = 0; i < 100; i++) {
    keys[i].n = 5;
    keys[i].p = malloc(8 * sizeof(char));
  }

  /*
  The phf_init_string() function strives to generate as compact a set of hash
  values as possible. If nkw represents the number of unique keywords, the
  resulting unique hash values will range from 0 to context.m-1, where context.m
  >= nkw. Generally context.m > nkw, so there will be context.m - nkw unused
  integers in the range of 0 to context.m-1.

  The 100 test keywords take values from "10000" to "10099". The integer array
  ki[] contains the set of indices associated with the keywords. In some cases
  two or more keywords may be associated with the same index.

  Unfortunately the unique hash values generated by the phf_init_string()
  function are arranged in random order relative to the keyword order. An
  indirection table must be generated to allow each hash value to access the
  correct index.
  */
  int kn = 10000;
  int ki[100];
  size_t nkw = 0;
  int l = 0;
  for(int i = 0; i < 10; i++) {
    for(int j = 0; j < 9; j++) {
      sprintf(keys[nkw].p, "%d", kn++);
      ki[nkw++] = l++;
    }
    sprintf(keys[nkw].p, "%d", kn++);
    ki[nkw++] = l - 5;
  }

  /*
  The following loop illustrates how the non unique indices are associated with
  the unique keywords.
  */
  for(int i = 0; i < nkw; i++) {
    printf("keys[%d].p = %s, index[%d] = %d\n", i, keys[i].p, i, ki[i]);
  }

  /*
  struct phf {
    bool nodiv;
    phf_seed_t seed;
    size_t r; number of elements in g
    size_t m; number of elements in perfect hash
    uint32_t* g; displacement map indexed by g(k) % r
    size_t d_max; maximum displacement value in g
    enum {
      PHF_G_UINT8_MOD_R = 1,
      PHF_G_UINT8_BAND_R,
      PHF_G_UINT16_MOD_R,
      PHF_G_UINT16_BAND_R,
      PHF_G_UINT32_MOD_R,
      PHF_G_UINT32_BAND_R,
    } g_op;
    const void* g_jmp;
  };
  This structure will contain all information generated by the phf_init_string()
  function and required by the phf_hash_string() function to return a hash value
  for each unique keyword. error == 0 means that phf_init_string() successfully
  generated the hash table in the phf structure and it is ready to support the
  phf_hash_string() function.
  */
  struct phf context;
  int error;
  if((error =
        phf_init_string(&context, keys, nkw, lambda, alpha, seed, nodiv))) {
    errx(1, "phf_init: %s", strerror(error));
  }

  /*
  Print some of the hash-table statistics.
  */
  printf("nodiv = %d\n", context.nodiv);
  printf("seed = %d\n", context.seed);
  printf("number of elements in g = %zu\n", context.r);
  printf("number of elements in hash = %zu\n", context.m);
  for(int i = 0; i < context.r; i++) {
    printf("g[%d] = %u\n", i, context.g[i]);
  }
  printf("d_max = %zu\n", context.d_max);

  /*
  This loop prints out the returned hash, keyword, and index values in keyword
  storage order. It is used to verify that all hash values are unique and in
  the interval 0 <= hash < context.m. It also illustrates the random order of
  hash values.
  */
  for(int i = 0; i < nkw; i++) {
    phf_hash_t hash = phf_hash_string(&context, keys[i]);
    printf("hash = %d, keys[%d].p = %s, index[%d] = %d\n", (int)hash, i,
           (char*)keys[i].p, i, ki[i]);
  }

  /*
  ind is a pointer to the indirection array of length context.m. Not all
  elements of ind[] are used because there are gaps in hash values returned from
  the phf_hash_string() function. To visually verify which entries of ind[] are
  not set or used, all values are initialized to -1.
  */
  int* ind;
  ind = malloc(context.m * sizeof(int));
  for(int i = 0; i < context.m; i++) {
    ind[i] = -1;
  }

  /*
  This loop evaluates the indirection table. Since ki[] contains the desired
  indices in keyword order and hash is evaluated in keyword order, ind[hash]
  will point to the desired indices.
  */
  for(int i = 0; i < nkw; i++) {
    phf_hash_t hash = phf_hash_string(&context, keys[i]);
    ind[(int)hash] = ki[i];
  }

  /*
  This loop is used to verify that the generated indirection table points to the
  desired indices.
  */
  for(int i = 0; i < nkw; i++) {
    phf_hash_t hash = phf_hash_string(&context, keys[i]);
    printf("key[%d] = %s points to index[%d] = %d\n", i, (char*)keys[i].p, i,
           ind[(int)hash]);
  }

  /*
  This loop displays entries in the indirection table. Negative values indicate
  unused entries.
  */
  for(int i = 0; i < context.m; i++) {
    printf("ind[%d] = %d\n", i, ind[i]);
  }

  /*
  Remove the hash table when finished.
  */
  phf_destroy(&context);

  return 0;
}
